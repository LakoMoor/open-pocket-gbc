"""Write (* blackbox *) declarations for the top modules of GHDL-generated netlists,
so slang can elaborate instances while yosys read_verilog loads the real netlist."""
import re, sys

out = sys.argv[1]
items = sys.argv[2:]          # file:module pairs
res = ["// generated by tools/mkstub.py - do not edit"]
for it in items:
    path, mod = it.split(':')
    s = open(path).read()
    m = re.search(r'^module ' + re.escape(mod) + r'\b(.*?)\);', s, re.S | re.M)
    assert m, it
    res.append('(* blackbox *)\nmodule ' + mod + m.group(1) + ');\nendmodule\n')
open(out, 'w').write('\n'.join(res))
