#!/usr/bin/env python3
"""Writes the menu icons into glyphs 1..31 of rtl/video/font8x8.hex (8 rows, MSB = left).

Codes are used by fw/src/osd.h (G_*). With bit 7 set in the OSD character, rows 0 and 7
are repeated into the 2 px cell padding, so the pill ends and lines join vertically.
"""
import os

ICONS = {
    1:  ("PILL_L",  [0x07, 0x1F, 0x3F, 0x7F, 0x7F, 0x3F, 0x1F, 0x07]),
    2:  ("PILL_R",  [0xE0, 0xF8, 0xFC, 0xFE, 0xFE, 0xFC, 0xF8, 0xE0]),
    3:  ("HLINE",   [0x00, 0x00, 0x00, 0xFF, 0x00, 0x00, 0x00, 0x00]),
    4:  ("CHEV_R",  [0x00, 0x30, 0x18, 0x0C, 0x18, 0x30, 0x00, 0x00]),
    5:  ("CHEV_L",  [0x00, 0x0C, 0x18, 0x30, 0x18, 0x0C, 0x00, 0x00]),
    6:  ("FOLDER",  [0x00, 0x70, 0xFF, 0x81, 0x81, 0x81, 0xFF, 0x00]),
    7:  ("CART",    [0xFC, 0x86, 0xBA, 0xBA, 0x82, 0x92, 0xFE, 0x00]),
    8:  ("SDCARD",  [0x3E, 0x6A, 0xEA, 0xFE, 0xFE, 0xFE, 0xFE, 0x00]),
    9:  ("PLAY",    [0x00, 0x60, 0x78, 0x7E, 0x78, 0x60, 0x00, 0x00]),
    10: ("RESET",   [0x3C, 0x42, 0xF2, 0x62, 0x02, 0x42, 0x3C, 0x00]),
    11: ("SAVE",    [0xFE, 0xC6, 0xC6, 0xFE, 0x82, 0xBA, 0x82, 0xFE]),
    12: ("DISPLAY", [0x00, 0xFE, 0x82, 0x82, 0x82, 0xFE, 0x38, 0x7C]),
    13: ("AUDIO",   [0x08, 0x1A, 0xF9, 0xF9, 0xF9, 0x1A, 0x08, 0x00]),
    14: ("PAD",     [0x00, 0x7E, 0xDB, 0x8D, 0xDB, 0xFF, 0xE7, 0x00]),
    15: ("GEAR",    [0x18, 0x7E, 0x66, 0xC3, 0xC3, 0x66, 0x7E, 0x18]),
    16: ("INFO",    [0x3C, 0x7E, 0xE7, 0xFF, 0xE7, 0xE7, 0x7E, 0x3C]),
    17: ("POWER",   [0x18, 0x5A, 0x99, 0x99, 0x81, 0x42, 0x3C, 0x00]),
    18: ("LIBRARY", [0x00, 0xDB, 0xDB, 0xDB, 0xDB, 0xDB, 0xFF, 0x00]),
    19: ("CHECK",   [0x00, 0x01, 0x03, 0x06, 0x8C, 0xD8, 0x70, 0x20]),
    20: ("BULLET",  [0x00, 0x00, 0x18, 0x3C, 0x3C, 0x18, 0x00, 0x00]),
    21: ("BLOCK",   [0xFF] * 8),
    22: ("THUMB",   [0x18] * 8),
    23: ("TRACK",   [0x08] * 8),
    24: ("STAR",    [0x10, 0x10, 0x38, 0xFE, 0x7C, 0x38, 0x6C, 0x44]),
    25: ("FLASH",   [0x7E, 0x42, 0x5A, 0x5A, 0x42, 0x7E, 0x24, 0x24]),
    26: ("UP",      [0x00, 0x18, 0x3C, 0x7E, 0x00, 0x00, 0x00, 0x00]),
    27: ("DOWN",    [0x00, 0x00, 0x00, 0x7E, 0x3C, 0x18, 0x00, 0x00]),
    28: ("MENU",    [0x00, 0x7E, 0x00, 0x7E, 0x00, 0x7E, 0x00, 0x00]),
    29: ("SQ_FULL", [0x00, 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x00]),
    30: ("SQ_EMPTY",[0x00, 0x7E, 0x42, 0x42, 0x42, 0x42, 0x7E, 0x00]),
    31: ("MOON",    [0x1C, 0x38, 0x70, 0x70, 0x70, 0x38, 0x1C, 0x00]),
}

root = os.path.join(os.path.dirname(__file__), "..")
path = os.path.join(root, "rtl", "video", "font8x8.hex")
rows = [l.strip() for l in open(path) if l.strip()]
assert len(rows) == 1024
for code, (name, bits) in ICONS.items():
    for r in range(8):
        rows[code * 8 + r] = "%02x" % bits[r]
open(path, "w").write("\n".join(rows) + "\n")

hdr = os.path.join(root, "fw", "src", "glyphs.h")
with open(hdr, "w") as f:
    f.write("// generated by tools/make_font_icons.py\n#pragma once\n")
    for code, (name, _) in ICONS.items():
        f.write("#define G_%s %d\n" % (name, code))
print("icons written")
