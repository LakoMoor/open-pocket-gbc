#!/usr/bin/env bash
# Assembles the boot ROM and writes rtl/sys/bootrom.vh (rebuild the bitstream afterwards).
set -euo pipefail
cd "$(dirname "$0")"
export PATH=/e/tools/rvgcc/xpack-riscv-none-elf-gcc-15.2.0-1/bin:$PATH
riscv-none-elf-gcc -march=rv32e -mabi=ilp32e -nostdlib -Wl,-Ttext=0x01000000 -o boot.elf boot.S
riscv-none-elf-objcopy -O binary boot.elf boot.bin
python - <<'PY'
import struct
b = open('boot.bin', 'rb').read(); b += b'\0' * (-len(b) % 4)
w = struct.unpack('<%dI' % (len(b) // 4), b)
o = ['// generated by fw/boot/make.sh (boot.S)', 'function automatic [31:0] bootrom(input [6:0] a);', '    case (a)']
o += ["        7'd%d: bootrom = 32'h%08x;" % (i, x) for i, x in enumerate(w)]
o += ["        default: bootrom = 32'h00000013;", '    endcase', 'endfunction']
open('../../rtl/sys/bootrom.vh', 'w').write('\n'.join(o) + '\n')
print(len(w), 'words')
PY
