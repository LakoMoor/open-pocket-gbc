// The renderer talks to the main process only through this API.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('studio', {
  status: () => ipcRenderer.invoke('status'),
  installBuild: which => ipcRenderer.invoke('install-build', which),
  install: items => ipcRenderer.invoke('install', items),
  installRelease: variant => ipcRenderer.invoke('install-release', variant),
  releaseInfo: () => ipcRenderer.invoke('release-info'),
  pick: kind => ipcRenderer.invoke('pick', kind),
  sd: (drive, source) => ipcRenderer.invoke('sd', drive, source),
  key: (k, down) => ipcRenderer.invoke('key', k, down),
  connect: () => ipcRenderer.invoke('connect'),
  shot: () => ipcRenderer.invoke('shot'),
  font: () => ipcRenderer.invoke('font'),
  open: url => ipcRenderer.invoke('open', url),
  ideFiles: () => ipcRenderer.invoke('ide-files'),
  ideRead: p => ipcRenderer.invoke('ide-read', p),
  ideWrite: (p, text) => ipcRenderer.invoke('ide-write', p, text),
  ideBuild: () => ipcRenderer.invoke('ide-build'),
  simLoad: opts => ipcRenderer.invoke('sim-load', opts),
  simSave: (flash, sd) => ipcRenderer.invoke('sim-save', flash, sd),
  simResetFlash: () => ipcRenderer.invoke('sim-reset-flash'),
  simSdOpen: sd => ipcRenderer.invoke('sim-sd-open', sd),
  rtlAvailable: () => ipcRenderer.invoke('rtl-available'),
  rtlBuild: () => ipcRenderer.invoke('rtl-build'),
  rtlStart: opts => ipcRenderer.invoke('rtl-start', opts),
  rtlKey: bits => ipcRenderer.invoke('rtl-key', bits),
  rtlRemote: ch => ipcRenderer.invoke('rtl-remote', ch),
  screen: on => ipcRenderer.invoke('screen', on),
  savePngs: files => ipcRenderer.invoke('save-pngs', files),
  saveVideo: bytes => ipcRenderer.invoke('save-video', bytes),
  cfgList: () => ipcRenderer.invoke('cfg-list'),
  cfgSet: (p, i, v) => ipcRenderer.invoke('cfg-set', p, i, v),
  rtlStop: () => ipcRenderer.invoke('rtl-stop'),
  on: (ch, fn) => ipcRenderer.on(ch, (_, d) => fn(d)),
});
